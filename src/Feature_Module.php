/**
 * ماژولِ فیچر — هم‌ترازِ ‎Schema_Provider‎، ولی برایِ زیرسیستم‌هایی که
 * چرخهٔ عمرشان *رندر* نیست.
 *
 * چرا یک انتزاعِ دوم لازم بود: هر ‎Schema_Provider‎ یک قرارداد دارد —
 * «رویِ ‎wp_head‎، اگر ‎applies()‎ بود، ‎nodes()‎ را بده». ولی فیچرهایِ
 * این فاز سه چرخهٔ عمرِ کاملاً متفاوت دارند: ‎llms.txt‎ یک endpointِ
 * مجازی است (‎template_redirect‎)، ‎robots‎ یک فیلترِ خروجیِ موجود است،
 * و ‎IndexNow‎ رویدادمحور است (‎transition_post_status‎ + ‎shutdown‎).
 * فشردنِ این‌ها در ‎applies()/nodes()‎ یعنی جعلِ یک چرخهٔ عمرِ مشترکی که
 * وجود ندارد.
 *
 * پس قرارداد این‌جا حداقلی است: «خودت هوک‌هایت را ثبت کن». همان الگویی
 * که ‎RankMath\Neutralizer::boot()‎ از قبل داشت، فقط رسمی‌شده.
 *
 * ثبت مثلِ Providerها: هر فایلِ ‎src/Feature/*.php‎ در انتهایِ خودش با
 * ‎add_filter('zig3d_ai_access/features', …)‎ خودش را اضافه می‌کند و
 * ‎Plugin‎ فقط پوشه را می‌گردد — افزودنِ فیچرِ جدید هیچ ویرایشی در
 * ‎Plugin‎ نمی‌خواهد.
 */
interface Feature_Module {

    /**
     * تنها متدِ قرارداد. این‌جا فقط هوک ثبت می‌شود — هیچ کوئری، هیچ
     * خروجی، هیچ کارِ سنگین. ‎boot()‎ رویِ *هر* درخواست اجرا می‌شود،
     * از جمله ادمین و AJAX و REST؛ خودِ فیچر باید بافتِ نامربوط را در
     * کال‌بکِ هوکش رد کند، نه با نبوتن.
     */
    public function boot(): void;
}
